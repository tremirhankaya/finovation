-- Guard: every dataset asset must already exist in dbo.assets.
IF EXISTS (
    SELECT 1
    FROM @Shocks s
    LEFT JOIN dbo.assets a ON a.asset_code = s.asset_code
    WHERE a.id IS NULL
)
BEGIN
    THROW 50002, 'Stress shock dataset contains an asset that does not exist in dbo.assets.', 1;
END;

-- Guard: both scenarios must exist before shock persistence.
IF EXISTS (
    SELECT 1
    FROM @Shocks s
    LEFT JOIN dbo.stress_scenarios ss ON ss.code = s.scenario_code
    WHERE ss.id IS NULL
)
BEGIN
    THROW 50003, 'Stress shock dataset contains an unknown scenario code.', 1;
END;

-- Update existing rows, if any.
UPDATE target
SET
    target.impact = source.impact,
    target.updated_at = SYSUTCDATETIME()
FROM dbo.stress_scenario_asset_shocks target
JOIN dbo.stress_scenarios scenario
    ON scenario.id = target.scenario_id
JOIN dbo.assets asset
    ON asset.id = target.asset_id
JOIN @Shocks source
    ON source.scenario_code = scenario.code
   AND source.asset_code = asset.asset_code;

-- Insert missing rows.
INSERT INTO dbo.stress_scenario_asset_shocks (
    scenario_id,
    asset_id,
    impact
)
SELECT
    scenario.id,
    asset.id,
    source.impact
FROM @Shocks source
JOIN dbo.stress_scenarios scenario
    ON scenario.code = source.scenario_code
JOIN dbo.assets asset
    ON asset.asset_code = source.asset_code
WHERE NOT EXISTS (
    SELECT 1
    FROM dbo.stress_scenario_asset_shocks existing
    WHERE existing.scenario_id = scenario.id
      AND existing.asset_id = asset.id
);

